def create_sample_files(sample_dir: Path | str) -> tuple[Path, Path]:
    sample_path = Path(sample_dir)
    sample_path.mkdir(parents=True, exist_ok=True)

    bom_path = sample_path / "sample_bom.xlsx"
    supply_path = sample_path / "sample_supply.xlsx"

    pd.DataFrame(build_sample_bom_data(), columns=BOM_COLUMNS).to_excel(bom_path, index=False)
    pd.DataFrame(build_sample_supply_data(), columns=SUPPLY_COLUMNS).to_excel(supply_path, index=False)

    return bom_path, supply_path


